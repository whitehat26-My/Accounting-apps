/**
 * Write `apps/web/out/_redirects` — the /api proxy for a Netlify deployment.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS IS A SCRIPT AND NOT THREE LINES OF netlify.toml.
 *
 * Netlify does not substitute environment variables into redirect targets. A
 * `to = "$API_ORIGIN/:splat"` in netlify.toml is sent to the browser as the
 * literal string `$API_ORIGIN`, and the deploy looks fine until somebody signs
 * in. Since every site sells to a different shop with a different API host, the
 * target cannot be a constant in a committed file — so it is written here, at
 * build time, when the environment is actually readable.
 *
 * THE PROXY IS WHY THERE IS NO CORS. `apps/web/src/lib/api.ts` fetches relative
 * `/api/...` paths, so the browser only ever sees the Netlify origin; Netlify
 * fetches the API server-side and returns the response as its own. Status 200
 * is what makes it a rewrite rather than a redirect — a 301/302 would send the
 * browser to the API host, which is a second origin, which is CORS, and which
 * also drops the cookie. This mirrors exactly what `next.config.ts` does with
 * `rewrites()` on the Docker path.
 *
 * `/api/v1/auth/login` → `${API_ORIGIN}/v1/auth/login`: the `/api` prefix is
 * a routing marker for the host and is stripped, because the API mounts its
 * routes at `/v1`. `:splat` is whatever `*` matched.
 * ---------------------------------------------------------------------------
 *
 * It REFUSES to write a file it cannot stand behind. A deployment whose proxy
 * target is missing or wrong is not a broken build — it is a green build and a
 * site where every screen loads, every login fails, and the reason is three
 * layers away from the error the shop sees. Failing the build is cheaper.
 */
import { writeFile, access } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const OUT = fileURLToPath(new URL('../apps/web/out', import.meta.url));

function die(message) {
  console.error(`\n  netlify-redirects: ${message}\n`);
  process.exit(1);
}

const raw = (process.env['API_ORIGIN'] ?? '').trim();
if (!raw) {
  die(
    'API_ORIGIN is not set.\n\n' +
      '  It is the address of the API container (Railway/Fly), e.g.\n' +
      '    API_ORIGIN=https://emil-api.up.railway.app\n\n' +
      '  Set it in Netlify under Site configuration → Environment variables,\n' +
      '  then redeploy. Without it the site builds and every login 404s.',
  );
}

let origin;
try {
  origin = new URL(raw);
} catch {
  die(`API_ORIGIN is not a URL: ${JSON.stringify(raw)}`);
}

// http would send session cookies and every invoice in clear text, and a
// browser on an https page will refuse the request anyway. Localhost is the
// one honest exception: it is how the export is rehearsed before deploying.
const local = origin.hostname === 'localhost' || origin.hostname === '127.0.0.1';
if (origin.protocol !== 'https:' && !local) {
  die(`API_ORIGIN must be https (got ${origin.protocol}//${origin.host})`);
}
if (origin.pathname !== '/' || origin.search || origin.hash) {
  die(`API_ORIGIN must be a bare origin with no path — got ${raw}`);
}

// Build first, then this. If `out/` is absent the build did not run, and
// writing the file would create the directory and hide that.
try {
  await access(OUT);
} catch {
  die(`${OUT} does not exist — run the web build before this script.`);
}

const target = origin.origin;
const body = `# Generated by scripts/netlify-redirects.mjs — do not edit.
# Proxy (status 200), not redirect: the browser stays on this origin, so no
# CORS and the session cookie is still first-party.
/api/*  ${target}/:splat  200
`;

await writeFile(join(OUT, '_redirects'), body, 'utf8');
console.log(`netlify-redirects: /api/* -> ${target}/:splat (200)`);
