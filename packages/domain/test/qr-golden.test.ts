/**
 * WHOLE SYMBOLS, FROM SOMEBODY ELSE'S ENCODER.
 *
 * ---------------------------------------------------------------------------
 * WHY THIS FILE EXISTS, WHICH IS A STORY WORTH KEEPING.
 *
 * `qr.test.ts` checked this encoder three ways — structure, the format
 * information against the published BCH table, and a round trip through a
 * decoder written separately from the encoder. All three passed for months.
 * Every QR this application drew was unscannable.
 *
 * The format information was written least-significant-bit first, and the test
 * read it back least-significant-bit first, so the two agreed with each other
 * about a convention they had both got backwards. The round-trip decoder took
 * the version from the module count, so it never noticed that symbols from
 * version 7 up were missing the version-information blocks the standard
 * requires. Two bugs, each invisible to a test written by the same hand as the
 * code — which is the whole hazard of testing an encoder with your own decoder.
 *
 * The fix is a test that cannot share a convention with the encoder because it
 * did not come from here at all. Each matrix below was produced by an
 * INDEPENDENT implementation (the `qrcode` Python library, a separate codebase
 * with its own reading of ISO/IEC 18004), forced to byte mode at EC level M,
 * and pasted in whole. A single wrong module anywhere — a mask bit, a format
 * bit, a missing version block, a misplaced alignment pattern — fails this.
 *
 * These are cross-implementation vectors, not extracts from the standard: they
 * prove this encoder agrees with a widely-used one, which is the property that
 * matters at a counter with a customer holding a phone. They were confirmed
 * from the other direction too, by decoding rendered symbols with OpenCV's
 * QR reader before they were pasted here.
 *
 * IF ONE OF THESE FAILS, do not adjust the expectation. Render both matrices
 * and put a real scanner on them.
 *
 * A NOTE ON MASK CHOICE. The standard says pick the mask with the lowest
 * penalty score, and implementations occasionally differ on ties — so a payload
 * where this encoder and the reference chose different masks is NOT a bug and
 * simply is not a vector. The four below are cases where the two agree, which
 * is what lets them be compared module for module.
 * ---------------------------------------------------------------------------
 */

