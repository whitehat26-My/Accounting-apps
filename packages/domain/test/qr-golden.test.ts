describe('golden symbols, module for module', () => {
  for (const vector of VECTORS) {
    it(`matches an independent encoder: ${vector.label}`, () => {
      const actual = encodeQr(vector.payload).map((row) =>
        row.map((dark) => (dark ? '#' : '.')).join(''),
      );

      expect(actual.length).toBe(17 + vector.version * 4);
      // Row by row rather than whole-matrix, so a failure names the row that
      // went wrong instead of printing 53 lines twice.
      vector.rows.forEach((expected, y) => {
        expect(actual[y], `row ${y} of ${vector.label}`).toBe(expected);
      });
    });
  }
});
